#!/usr/bin/env python3
"""Sync the YunoHost wishlist into this board.

- Fetches upstream wishlist.toml (YunoHost/apps).
- New upstream entries land in "To categorize" automatically (marked NEW).
- Your categories live in categorize.toml:  app-key = "category"
- Regenerates README.md. Run daily via GitHub Action; also runnable locally.
"""
import datetime
import json
import pathlib
import tomllib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent
WISHLIST_URL = "https://raw.githubusercontent.com/YunoHost/apps/main/wishlist.toml"

CAT_TITLES = {
    "synchronization": "Synchronization", "publishing": "Publishing",
    "communication": "Communication", "office": "Office",
    "productivity_and_management": "Productivity & management",
    "small_utilities": "Small utilities", "reading": "Reading",
    "education": "Education", "multimedia": "Multimedia",
    "social_media": "Social media", "games": "Games", "dev": "Development",
    "system_tools": "System tools", "iot": "IoT", "wat": "Wat",
    "": "To categorize",
}


def fetch(url, token=None):
    req = urllib.request.Request(url, headers={"User-Agent": "wishlist-board-sync"})
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read()), None
    except urllib.error.HTTPError as e:
        return None, e.code


def stability(entry, now):
    """Cheap maturity tag from release dates. Tag is advisory, not gospel."""
    rel = entry.get("reldate")
    if not rel:
        return ""
    gap = entry.get("gap_days")
    age = (now - datetime.date.fromisoformat(rel)).days
    if age > 1825:
        return " `dormant`"
    if age > 730:
        return " `quiet`"
    if gap and gap >= 180:
        return " `slow-releases`"
    return ""


def upstream_query(upstream):
    u = (upstream or "").strip("/")
    if u.startswith("https://github.com/") and u.count("/") == 3:
        return u[len("https://github.com/"):]
    return None


def main():
    import os
    token = os.environ.get("GITHUB_TOKEN") or None

    with urllib.request.urlopen(urllib.request.Request(
            WISHLIST_URL, headers={"User-Agent": "wishlist-board-sync"}), timeout=30) as r:
        wish = tomllib.loads(r.read().decode())

    categorize = tomllib.loads((ROOT / "categorize.toml").read_text()) if (ROOT / "categorize.toml").exists() else {}
    seen_file = ROOT / "seen.txt"
    seen = set(seen_file.read_text().split()) if seen_file.exists() else set()
    act_file = ROOT / "activity.json"
    activity = json.loads(act_file.read_text()) if act_file.exists() else {}

    new = {k for k in wish if k not in seen}
    ghosts = sorted(seen - set(wish))

    # Fill activity data for apps we know nothing about (capped per run).
    # shortcut: only fills missing entries, 50/run; reruns fill the rest. Upgrade: backfill loop if ever stale.
    if token:
        todo = [k for k in wish if not activity.get(k, {}).get("reldate")][:50]
        for k in todo:
            slug = upstream_query(wish[k].get("upstream", ""))
            if not slug:
                continue
            releases, err = fetch(f"https://api.github.com/repos/{slug}/releases?per_page=3", token)
            if err or not isinstance(releases, list) or not releases:
                continue
            dates = [r.get("published_at", "")[:10] for r in releases[:3] if r.get("published_at")]
            e = activity.setdefault(k, {"slug": slug})
            if dates:
                e["reldate"] = dates[0]
            if len(dates) >= 2:
                d0, d1 = (datetime.date.fromisoformat(d) for d in dates[:2])
                e["gap_days"] = (d0 - d1).days

    now = datetime.date.today()
    lines = [
        "# YunoHost wishlist board",
        "",
        "Personal reference for what to package next. Generated by `sync.py` "
        "(daily GitHub Action) from the [official wishlist](https://apps.yunohost.org/wishlist). "
        "Upstream churn column = days between the two latest upstream releases.",
        "",
        "**Workflow**",
        "",
        "1. New wishlist requests appear under **To categorize** (marked `NEW`) — nothing gets lost.",
        '2. To categorize one, move its line into `categorize.toml` (e.g. `myapp = "multimedia"`) and commit.',
        "3. The Action regenerates this README within a day (or run `python sync.py` manually).",
        "",
    ]

    def fmt(k):
        v, a = wish[k], activity.get(k, {})
        desc = " ".join(v.get("description", "").split())
        bits = [f"- **{v.get('name', k)}** — {desc}".rstrip()]
        if v.get("upstream"):
            bits.append(f" [upstream]({v['upstream']})")
        added = v.get("added_date")
        if added:
            bits.append(f" · requested {datetime.date.fromtimestamp(added)}")
        if a.get("reldate"):
            gap = a.get("gap_days")
            bits.append(f" · last release {a['reldate']}" + (f" ({gap}d gap)" if gap else ""))
        bits.append(stability(a, now))
        return "".join(bits)

    uncat = sorted((k for k in wish if k not in categorize),
                   key=lambda k: wish[k].get("added_date", 0), reverse=True)
    lines += ["## To categorize", ""]
    for k in uncat:
        lines.append(fmt(k) + ("  `NEW`" if k in new else ""))
    lines.append("")

    bycat = {}
    for k, cat in categorize.items():
        if k in wish:
            bycat.setdefault(cat, []).append(k)
    for cat in list(CAT_TITLES) + sorted(set(bycat) - set(CAT_TITLES)):
        if not cat or cat == "":
            continue
        apps = sorted(bycat.get(cat, []))
        lines += [f"## {CAT_TITLES.get(cat, cat)} ({len(apps)})", ""]
        lines += [fmt(k) for k in apps] + [""]

    if ghosts:
        lines += [f"## Dropped from upstream wishlist ({len(ghosts)})", "",
                  *[f"- {k}" for k in ghosts], ""]

    lines += [f"_Last synced {now} · {len(wish)} upstream entries · {len(new)} new this run._"]

    (ROOT / "README.md").write_text("\n".join(lines) + "\n")
    seen_file.write_text("\n".join(sorted(set(wish))) + "\n")
    act_file.write_text(json.dumps(activity, indent=0, sort_keys=True) + "\n")
    print(f"synced: {len(wish)} apps, {len(new)} new, {len(uncat)} to categorize, {len(ghosts)} ghosts")


if __name__ == "__main__":
    main()
